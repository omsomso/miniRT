#include "../libft.h"

int	gnl_find_char(const char *s, int c, int n)
{
	int				i;
	unsigned char	tmp;

	i = -1;
	tmp = (unsigned char) c;
	while (i == -1 || s[i] || i < n)
	{
		i++;
		if (s[i] == tmp)
			return (i);
	}
	return (0);
}
