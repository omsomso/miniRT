#include "../libft.h"

char	*ft_strchr(const char *s, int c)
{
	int				i;
	unsigned char	tmp;

	i = -1;
	tmp = (unsigned char) c;
	while (i == -1 || s[i])
	{
		i++;
		if (s[i] == tmp)
			return ((char *) &s[i]);
	}
	return (NULL);
}
